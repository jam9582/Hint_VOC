-- schema.sql을 이미 실행한 DB에만 실행한다. 새 DB는 schema.sql에 이미 들어 있다.

begin;

-- 접수 정보 수정 기록. changes에는 [{label, before, after}]가 들어간다.
create table public.voc_edit_log (
  log_id     integer generated by default as identity primary key,
  voc_id     varchar(20) not null references public.voc (voc_id) on delete cascade,
  changes    jsonb       not null,
  reason     varchar(200) not null,
  changed_by varchar(30) not null,
  changed_at timestamptz not null default now()
);

create index voc_edit_log_voc_id_idx on public.voc_edit_log (voc_id);

alter table public.voc_edit_log enable row level security;

revoke all on public.voc_edit_log from anon, authenticated;
grant select on public.voc_edit_log to authenticated;
grant select, insert, update, delete on public.voc_edit_log to service_role;

create policy "로그인 사용자 읽기" on public.voc_edit_log for select to authenticated using (true);

-- 접수 정보, 팀 구성, 수정 기록을 한 번에 저장한다.
-- p_stage가 현재 단계와 다르면 실패한다. 기한을 옛 단계 기준으로 덮어쓰는 일을 막는다.
create function public.edit_voc(
  p_voc_id text,
  p_stage text,
  p_voc jsonb,
  p_team text,
  p_changes jsonb,
  p_reason text,
  p_changed_by text
)
returns void
language plpgsql
set search_path = ''
as $$
begin
  update public.voc
     set channel = p_voc ->> 'channel',
         grade = p_voc ->> 'grade',
         owner = p_voc ->> 'owner',
         vin = p_voc ->> 'vin',
         mileage_km = (p_voc ->> 'mileage_km')::integer,
         voc_type = p_voc ->> 'voc_type',
         system = p_voc ->> 'system',
         part_name = p_voc ->> 'part_name',
         part_no = p_voc ->> 'part_no',
         symptom = p_voc ->> 'symptom',
         frequency = p_voc ->> 'frequency',
         reproduced = p_voc ->> 'reproduced',
         type_detail = p_voc -> 'type_detail',
         media_links = p_voc ->> 'media_links',
         similar_ids = p_voc ->> 'similar_ids',
         due_at = (p_voc ->> 'due_at')::date
   where voc_id = p_voc_id
     and stage = p_stage;

  if not found then
    raise exception 'VOC가 없거나 단계가 이미 바뀌었습니다: %', p_voc_id;
  end if;

  update public.voc_8d
     set team = nullif(p_team, '')
   where voc_id = p_voc_id;

  insert into public.voc_edit_log (voc_id, changes, reason, changed_by)
  values (p_voc_id, p_changes, p_reason, p_changed_by);
end;
$$;

revoke execute on function public.edit_voc(text, text, jsonb, text, jsonb, text, text)
  from public, anon, authenticated;
grant execute on function public.edit_voc(text, text, jsonb, text, jsonb, text, text)
  to service_role;

commit;
