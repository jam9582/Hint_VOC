              public.voc_8d, public.voc_stage_log, public.profiles
  from anon, authenticated;

grant select on public.code, public.vehicle, public.vehicle_part, public.voc,
                public.voc_8d, public.voc_stage_log, public.profiles
  to authenticated;

grant select, insert, update, delete
  on public.code, public.vehicle, public.vehicle_part, public.voc,
     public.voc_8d, public.voc_stage_log, public.profiles
  to service_role;

create policy "로그인 사용자 읽기" on public.code          for select to authenticated using (true);
