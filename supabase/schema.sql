create function public.assert_code(p_group text, p_value text)
returns void
language plpgsql
set search_path = ''
as $$
begin
  if p_value is not null and not exists (
    select 1 from public.code where code_group = p_group and code = p_value
  ) then
    raise exception 'code 표에 없는 값입니다: % = %', p_group, p_value;
  end if;
end;
$$;

create function public.check_voc_codes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform public.assert_code('channel', new.channel);
  perform public.assert_code('grade', new.grade);
  perform public.assert_code('voc_type', new.voc_type);
  perform public.assert_code('system', new.system);
  perform public.assert_code('frequency', new.frequency);
  perform public.assert_code('reproduced', new.reproduced);
  perform public.assert_code('stage', new.stage);
  return new;
end;
$$;

create function public.check_voc_8d_codes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform public.assert_code('d4_method', new.d4_method);
  perform public.assert_code('d4_verified', new.d4_verified);
  perform public.assert_code('d6_result', new.d6_result);
  perform public.assert_code('d8_customer', new.d8_customer);
  return new;
end;
$$;

create function public.check_stage_log_codes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform public.assert_code('stage', new.from_stage);
  perform public.assert_code('stage', new.to_stage);
  return new;
end;
$$;

create function public.check_vehicle_codes()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  perform public.assert_code('shift', new.shift);
  return new;
end;
$$;

create trigger voc_check_codes before insert or update on public.voc
  for each row execute function public.check_voc_codes();
create trigger voc_8d_check_codes before insert or update on public.voc_8d
  for each row execute function public.check_voc_8d_codes();
create trigger voc_stage_log_check_codes before insert or update on public.voc_stage_log
  for each row execute function public.check_stage_log_codes();
create trigger vehicle_check_codes before insert or update on public.vehicle
  for each row execute function public.check_vehicle_codes();

-- ---------------------------------------------------------------------------
-- 계정이 생기면 profiles 줄을 자동으로 만든다. 처음에는 항상 일반 계정이다.
-- ---------------------------------------------------------------------------

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name, role)
  values (
    new.id,
    left(coalesce(nullif(new.raw_user_meta_data ->> 'name', ''), split_part(new.email, '@', 1)), 30),
    'user'
  );
  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- 여러 표를 한 번에 저장하는 함수 (15장 결정 3)
-- 필수 항목 검사와 기한 계산은 이 함수를 부르기 전에 사이트 서버 코드가 한다.
-- ---------------------------------------------------------------------------

create function public.register_voc(p_voc jsonb, p_team text, p_changed_by text)
returns varchar
language plpgsql
set search_path = ''
as $$
declare
  v_voc_id varchar(20);
begin
  insert into public.voc (
    received_at, channel, grade, owner, vin, mileage_km, voc_type, system,
    part_name, part_no, symptom, frequency, reproduced, type_detail,
    media_links, similar_ids, stage, due_at
  ) values (
    coalesce((p_voc ->> 'received_at')::timestamptz, now()),
    p_voc ->> 'channel',
    p_voc ->> 'grade',
    p_voc ->> 'owner',
    p_voc ->> 'vin',
    (p_voc ->> 'mileage_km')::integer,
    p_voc ->> 'voc_type',
    p_voc ->> 'system',
    p_voc ->> 'part_name',
    p_voc ->> 'part_no',
    p_voc ->> 'symptom',
    p_voc ->> 'frequency',
    p_voc ->> 'reproduced',
    p_voc -> 'type_detail',
    p_voc ->> 'media_links',
    p_voc ->> 'similar_ids',
    'D3',
    (p_voc ->> 'due_at')::date
  )
  returning voc_id into v_voc_id;

  insert into public.voc_8d (voc_id, team) values (v_voc_id, nullif(p_team, ''));

  insert into public.voc_stage_log (voc_id, from_stage, to_stage, changed_by)
  values (v_voc_id, null, 'D3', p_changed_by);

  return v_voc_id;
end;
$$;

-- p_from_stage가 현재 단계와 다르면 실패한다. 두 사람이 같은 VOC를 동시에 넘기는 일을 막는다.
-- p_8d에 들어 있는 열만 바뀐다. 값을 비우려면 그 열을 null로 넣는다.
create function public.advance_voc_stage(
  p_voc_id text,
  p_from_stage text,
  p_to_stage text,
  p_due_at date,
  p_8d jsonb,
  p_changed_by text,
  p_note text default null
)
returns void
language plpgsql
set search_path = ''
as $$
declare
  v public.voc_8d;
begin
  update public.voc
     set stage = p_to_stage,
         due_at = p_due_at,
         closed_at = case when p_to_stage = '종결' then now() end
   where voc_id = p_voc_id
     and stage = p_from_stage;

  if not found then
    raise exception 'VOC가 없거나 단계가 이미 바뀌었습니다: %', p_voc_id;
  end if;

  select * into strict v from public.voc_8d where voc_id = p_voc_id for update;
  v := jsonb_populate_record(v, coalesce(p_8d, '{}'::jsonb));

  update public.voc_8d
     set team = v.team,
         d3_scope = v.d3_scope,
         d3_action = v.d3_action,
         d3_done_at = v.d3_done_at,
         d4_occur_cause = v.d4_occur_cause,
         d4_escape_cause = v.d4_escape_cause,
         d4_method = v.d4_method,
         d4_verified = v.d4_verified,
         d4_done_at = v.d4_done_at,
         d5_occur_action = v.d5_occur_action,
         d5_escape_action = v.d5_escape_action,
         d6_cutover = v.d6_cutover,
         d6_criteria = v.d6_criteria,
         d6_result = v.d6_result,
         d6_evidence = v.d6_evidence,
         d7_docs = v.d7_docs,
         d7_horizontal = v.d7_horizontal,
         d8_customer = v.d8_customer
   where voc_id = p_voc_id;

  insert into public.voc_stage_log (voc_id, from_stage, to_stage, changed_by, note)
  values (p_voc_id, p_from_stage, p_to_stage, p_changed_by, p_note);
end;
$$;

