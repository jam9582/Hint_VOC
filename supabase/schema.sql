create table public.code (
  code_group varchar(30) not null,
  code       varchar(20) not null,
  label      varchar(50),
  sort       integer,
  active     boolean default true,
  primary key (code_group, code)
);

create table public.vehicle (
  vin        varchar(17) primary key check (char_length(vin) = 17),
  model      varchar(30),
  model_year integer,
  prod_date  date,
  plant      varchar(20),
  line       varchar(20),
  shift      varchar(20)
);

create table public.vehicle_part (
  vin           varchar(17) not null references public.vehicle (vin) on delete cascade,
  part_no       varchar(20) not null,
  part_name     varchar(50),
  part_lot      varchar(30),
  supplier      varchar(50),
  received_date date,
  primary key (vin, part_no)
);

-- VOC 번호. 같은 해 번호를 만드는 동안 잠금을 걸어 동시 등록에도 중복되지 않는다.
create function public.next_voc_id()
returns varchar
language plpgsql
set search_path = ''
as $$
declare
  v_year text := to_char(now() at time zone 'Asia/Seoul', 'YYYY');
  v_next integer;
begin
  perform pg_advisory_xact_lock(hashtext('voc_id:' || v_year));
  select coalesce(max(split_part(voc_id, '-', 3)::integer), 0) + 1
    into v_next
    from public.voc
   where voc_id like 'VOC-' || v_year || '-%';
  return 'VOC-' || v_year || '-' || lpad(v_next::text, greatest(4, length(v_next::text)), '0');
end;
$$;

-- vin은 vehicle을 참조하지 않는다. 이력이 없는 차량도 접수해야 한다. (PRD 7-8)
create table public.voc (
  voc_id      varchar(20) primary key default public.next_voc_id(),
  received_at timestamptz not null default now(),
  channel     varchar(20) not null,
  grade       varchar(20) not null,
  owner       varchar(30) not null,
  vin         varchar(17) not null check (char_length(vin) = 17),
  mileage_km  integer     not null check (mileage_km >= 0),
  voc_type    varchar(20) not null,
  system      varchar(20) not null,
  part_name   varchar(50) not null,
  part_no     varchar(20),
  symptom     text        not null check (char_length(symptom) <= 2000),
  frequency   varchar(20) not null,
  reproduced  varchar(20) not null,
  type_detail jsonb,
  media_links text,
  similar_ids varchar(200),
  stage       varchar(20) not null,
  due_at      date        not null,
  created_at  timestamptz not null default now(),
  closed_at   timestamptz,
  alerted_on  date
);

create table public.voc_8d (
  voc_id           varchar(20) primary key references public.voc (voc_id) on delete cascade,
  team             varchar(200),
  d3_scope         text check (char_length(d3_scope) <= 2000),
  d3_action        text check (char_length(d3_action) <= 2000),
  d3_done_at       timestamptz,
  d4_occur_cause   text check (char_length(d4_occur_cause) <= 2000),
  d4_escape_cause  text check (char_length(d4_escape_cause) <= 2000),
  d4_method        varchar(20),
  d4_verified      varchar(20),
  d4_done_at       timestamptz,
  d5_occur_action  text check (char_length(d5_occur_action) <= 2000),
  d5_escape_action text check (char_length(d5_escape_action) <= 2000),
  d6_cutover       varchar(50),
  d6_criteria      text check (char_length(d6_criteria) <= 2000),
  d6_result        varchar(20),
  d6_evidence      text check (char_length(d6_evidence) <= 2000),
  d7_docs          varchar(200),
  d7_horizontal    varchar(200),
  d8_customer      varchar(20)
);

create table public.voc_stage_log (
  log_id     integer generated by default as identity primary key,
  voc_id     varchar(20) not null references public.voc (voc_id) on delete cascade,
  from_stage varchar(20),
  to_stage   varchar(20) not null,
  changed_by varchar(30) not null,
  changed_at timestamptz not null default now(),
  note       varchar(200)
);

create table public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  name       varchar(30) not null,
  role       varchar(10) not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

create index voc_vin_idx on public.voc (vin);
create index voc_part_no_idx on public.voc (part_no);
create index voc_stage_idx on public.voc (stage);
create index voc_stage_log_voc_id_idx on public.voc_stage_log (voc_id);
create index vehicle_part_lot_idx on public.vehicle_part (part_no, part_lot);

